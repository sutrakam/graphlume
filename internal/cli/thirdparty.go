package cli

// The dependency inventory is generated, not written. A hand-maintained list
// is wrong within a month and nobody notices, because nothing checks it. This
// makes the file a build output and `--check` makes CI the thing that notices.

import (
	"context"
	"encoding/json"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"slices"
	"sort"
	"strings"
	"time"

	"github.com/sutrakam/graphlume/internal/analyze/licenses"

	"github.com/spf13/cobra"
)

// thirdPartyFile is the inventory's path, relative to the repository root.
const thirdPartyFile = "THIRD_PARTY.md"

// moduleInfo is the slice of `go list -m -json all` this inventory needs.
type moduleInfo struct {
	Path    string `json:"Path"`
	Version string `json:"Version"`
	Main    bool   `json:"Main"`
	// Indirect modules are still shipped in the binary, so they are listed.
	Indirect bool `json:"Indirect"`
	// License is the SPDX expression found in the local module cache, or
	// empty. Not part of `go list` output.
	License string `json:"-"`
}

// listModules returns every module in the build graph except the main module.
func listModules(root string) ([]moduleInfo, error) {
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()
	cmd := exec.CommandContext(ctx, "go", "list", "-m", "-json", "all")
	cmd.Dir = root
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list -m: %w", err)
	}

	var mods []moduleInfo
	dec := json.NewDecoder(strings.NewReader(string(out)))
	for dec.More() {
		var m moduleInfo
		if err := dec.Decode(&m); err != nil {
			return nil, fmt.Errorf("decode go list output: %w", err)
		}
		if m.Main || m.Version == "" {
			continue
		}
		mods = append(mods, m)
	}
	return mods, nil
}

// renderThirdParty produces the inventory. Sorted by module path so the output
// is byte-identical across runs and a diff means a real dependency change.
func renderThirdParty(mods []moduleInfo) string {
	sorted := make([]moduleInfo, len(mods))
	copy(sorted, mods)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Path < sorted[j].Path })

	var b strings.Builder
	b.WriteString("# Third-party dependencies\n\n")
	b.WriteString("Generated by `graphlume licenses`. Do not edit by hand —\n")
	b.WriteString("CI asserts this file matches the module graph.\n\n")
	b.WriteString("Every module below is compiled into the released binary.\n")
	b.WriteString("Licences are read from the local module cache; \"unknown\" means none\n")
	b.WriteString("was found there. Consult each module's own repository to confirm.\n\n")
	b.WriteString("| Module | Version | Direct | Licence |\n")
	b.WriteString("|---|---|---|---|\n")
	for _, m := range sorted {
		direct := "yes"
		if m.Indirect {
			direct = "no"
		}
		lic := m.License
		if lic == "" {
			lic = "unknown"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", m.Path, m.Version, direct, lic)
	}
	return b.String()
}

// detectModuleLicenses fills in each module's licence from the local module
// cache. Nothing is downloaded and no toolchain is run for it.
func detectModuleLicenses(ctx context.Context, root string, mods []moduleInfo) {
	in := make([]licenses.Dependency, len(mods))
	for i, m := range mods {
		in[i] = licenses.Dependency{Name: m.Path, Version: m.Version, Ecosystem: "go", Manifest: "go.mod"}
	}
	if ctx == nil {
		ctx = context.Background()
	}
	rs, _ := licenses.Resolve(ctx, licenses.EnvFromOS(root), in)
	for i := range mods {
		if rs[i].Source != licenses.SourceUnknown {
			mods[i].License = rs[i].License
		}
	}
}

// inventoryRows reduces an inventory to its module, version and direct
// columns. The licence column depends on what the local module cache holds,
// which differs between a laptop and CI, so --check compares the module graph
// only; a file written before the licence column existed still checks.
func inventoryRows(doc string) []string {
	var rows []string
	for _, line := range strings.Split(doc, "\n") {
		if !strings.HasPrefix(line, "| `") {
			continue
		}
		cells := strings.Split(line, "|")
		if len(cells) < 5 {
			continue
		}
		rows = append(rows, strings.TrimSpace(cells[1])+"|"+strings.TrimSpace(cells[2])+"|"+strings.TrimSpace(cells[3]))
	}
	return rows
}

func newLicensesCmd(g *Global) *cobra.Command {
	var check bool
	cmd := &cobra.Command{
		Use:   "licenses",
		Short: "Report dependency licences, or regenerate the third-party inventory",
		Long: `Writes THIRD_PARTY.md from the module graph, with the licence of each
module as found in the local Go module cache.

With --check, verifies the committed file lists the current module graph and
exits non-zero if it does not. That is the form CI runs. The licence column is
not compared: it depends on what this machine's module cache holds.

With --json, writes nothing and runs no toolchain: it prints the licence of
every dependency the index declares (go.mod, package.json, requirements.txt,
pyproject.toml, Cargo.toml, pom.xml, build.gradle) as JSON.

LICENCES ARE READ ONLY FROM FILES ALREADY ON THIS MACHINE. In order of trust:
the dependency's own metadata (an installed node_modules package.json, a
package-lock.json licence field, a project virtualenv's METADATA, a crate's
Cargo.toml in the Cargo registry cache, a POM in the Maven or Gradle cache),
then licence files (Go module cache, vendor/, node_modules), identified by a
built-in classifier and graded exact, high, medium or low. Nothing is
downloaded and no package manager is run. A licence not found locally is
"unknown", with the reason.`,
		RunE: func(cmd *cobra.Command, _ []string) error {
			root := g.Config().RepoRoot
			if g.JSON && !check {
				return licenseReport(cmd, g)
			}
			mods, err := listModules(root)
			if err != nil {
				return err
			}
			path := filepath.Join(root, thirdPartyFile)

			if check {
				want := renderThirdParty(mods)
				have, err := os.ReadFile(path) // #nosec G304 -- path is repo-root relative and constant
				if err != nil {
					return fmt.Errorf("read %s: %w", thirdPartyFile, err)
				}
				if !slices.Equal(inventoryRows(string(have)), inventoryRows(want)) {
					return fmt.Errorf("%s is stale; run: graphlume licenses", thirdPartyFile)
				}
				fmt.Fprintf(cmd.OutOrStdout(), "%s is current (%d modules)\n", thirdPartyFile, len(mods))
				return nil
			}

			detectModuleLicenses(cmd.Context(), root, mods)
			want := renderThirdParty(mods)
			if err := os.WriteFile(path, []byte(want), 0o600); err != nil {
				return fmt.Errorf("write %s: %w", thirdPartyFile, err)
			}
			fmt.Fprintf(cmd.OutOrStdout(), "wrote %s (%d modules)\n", thirdPartyFile, len(mods))
			return nil
		},
	}
	cmd.Flags().BoolVar(&check, "check", false, "verify the committed file is current instead of writing it")
	return cmd
}
